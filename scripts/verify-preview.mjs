function browser(storage = new Map()) {
  const network = [];
  const localStorage = { getItem: key => storage.get(key) || null, setItem: (key, value) => storage.set(key, value), removeItem: key => storage.delete(key) };
  const window = { fetch: async input => { network.push(String(input)); assert.equal(String(input), '/preview-data.json', 'No API or customer data may reach a network'); return new Response(JSON.stringify(data)); } };
  vm.runInNewContext(source, { window, localStorage, location: { href: 'https://preview.example/', origin: 'https://preview.example' }, URL, Response, Request, Headers, DOMException, crypto: {getRandomValues: webcrypto.getRandomValues.bind(webcrypto)}, Intl, FileReader: class { readAsDataURL() { this.result = 'data:image/png;base64,iVBORw0KGgo='; this.onload(); } } });
  const request = async (path, method = 'GET', body, key) => {
    const result = await window.fetch('https://preview.example/api' + path, { method, body: body === undefined ? undefined : typeof body === 'string' ? body : JSON.stringify(body), headers: key ? { 'Idempotency-Key': key } : {} });
    return { status: result.status, body: await result.json() };
  };
  const ok = async (...args) => { const response = await request(...args); assert.equal(response.status, 200, JSON.stringify(response)); return response.body; };
  return { window, request, ok, network, storage };
}
